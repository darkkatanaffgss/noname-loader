const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

function runSetup({ force = false } = {}) {
  const rootDir = path.resolve(__dirname, '..');
  const envPath = path.join(rootDir, 'api-server', '.env');
  const pubConfigPath = path.join(rootDir, 'sdk', 'public-config.json');

  if (!force && fs.existsSync(envPath) && fs.existsSync(pubConfigPath)) {
    return { skipped: true, envPath, pubConfigPath };
  }

  const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519', {
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' }
  });

  const adminSecret = crypto.randomBytes(32).toString('hex');
  const apiBaseUrl = process.env.NONAME_API_URL || 'http://127.0.0.1:3840';

  const envContent = [
    '# Auto-generated by scripts/setup-keys.js — NEVER commit this file to GitHub!',
    'PORT=3840',
    'ADMIN_ALLOWED_IPS=127.0.0.1,::1',
    `ADMIN_SECRET=${adminSecret}`,
    `ED25519_PRIVATE_KEY=${Buffer.from(privateKey, 'utf8').toString('base64')}`,
    `ED25519_PUBLIC_KEY=${Buffer.from(publicKey, 'utf8').toString('base64')}`
  ].join('\n') + '\n';

  const envDir = path.dirname(envPath);
  if (!fs.existsSync(envDir)) fs.mkdirSync(envDir, { recursive: true });
  fs.writeFileSync(envPath, envContent, 'utf8');

  const pubDir = path.dirname(pubConfigPath);
  if (!fs.existsSync(pubDir)) fs.mkdirSync(pubDir, { recursive: true });

  const publicConfig = {
    apiBaseUrl,
    pinnedCertSha256: '',
    ed25519PublicKeyBase64: Buffer.from(publicKey, 'utf8').toString('base64')
  };
  fs.writeFileSync(pubConfigPath, JSON.stringify(publicConfig, null, 2) + '\n', 'utf8');

  return { skipped: false, envPath, pubConfigPath, adminSecret };
}

if (require.main === module) {
  const force = process.argv.includes('--force');
  const res = runSetup({ force });
  if (res.skipped) {
    console.log('[setup] api-server/.env and sdk/public-config.json already exist. Run with --force to rotate keys.');
  } else {
    console.log('\n================================================');
    console.log('  Noname Loader — Cryptographic Setup Complete');
    console.log('================================================');
    console.log('Generated unique Ed25519 keypair + Admin Secret:');
    console.log(`  Backend .env  : ${res.envPath}`);
    console.log(`  Client Config : ${res.pubConfigPath} (Public Key only)`);
    console.log(`  ADMIN_SECRET  : ${res.adminSecret}`);
    console.log('\nKeep api-server/.env private. Server is ready to start.\n');
  }
}

module.exports = { runSetup };
